// Export browser-ready images; original photos and PDFs are kept unchanged.
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const context = { window: {} };
vm.runInNewContext(await readFile(path.join(dist, 'site-data.js'), 'utf8'), context, { timeout: 1000 });
const data = context.window.SITE_DATA;
const previous = { window: {} };
try { vm.runInNewContext(await readFile(path.join(dist, 'asset-previews.js'), 'utf8'), previous, { timeout: 1000 }); } catch { /* First export. */ }
const files = {};
const urls = (value) => typeof value === 'string' ? [value] : value && typeof value === 'object' ? Object.values(value) : [];
const sources = [...urls(data.profile?.image).map((url) => ({ url, photo: true })),
  ...(data.publications || []).flatMap((paper) => urls(paper.image).map((url) => ({ url, photo: false })))];
const run = (command, args) => {
  const result = spawnSync(command, args, { encoding: 'utf8' });
  if (result.error) throw new Error(`需要 ${command}：PDF 预览依赖 Poppler，照片优化依赖 ImageMagick。`);
  if (result.status !== 0) throw new Error(result.stderr || `${command} failed`);
};
let updated = 0;
for (const item of sources) {
  const url = String(item.url || '').trim().replace(/^\/(?=assets\/)/, '');
  if (!url || /^https?:\/\//i.test(url)) continue;
  const ext = path.extname(url).toLowerCase();
  if (ext !== '.pdf' && !(item.photo && ['.jpg', '.jpeg', '.png', '.webp'].includes(ext))) continue;
  const source = path.resolve(dist, url);
  const relative = path.relative(dist, source);
  if (!url.startsWith('assets/') || relative.startsWith('..') || path.isAbsolute(relative)) throw new Error(`请使用 dist 内的 assets/ 相对路径：${url}`);
  let content;
  try { content = await readFile(source); } catch { throw new Error(`配置引用的文件不存在：${url}`); }
  const hash = createHash('sha256').update(content).digest('hex');
  const base = path.basename(url, path.extname(url));
  const preview = ext === '.pdf' ? `assets/publications/previews/${base}.png`
    : `assets/previews/${base}${['.jpg', '.jpeg'].includes(ext) ? '.jpg' : '.png'}`;
  const entry = { preview, kind: ext === '.pdf' ? 'pdf' : 'image', sha256: hash };
  files[url] = entry;
  let exists = false;
  try { await access(path.join(dist, preview)); exists = true; } catch { /* Needs export. */ }
  const old = previous.window.ASSET_PREVIEWS?.files?.[url];
  if (exists && old?.sha256 === hash && old.preview === preview) continue;
  const output = path.join(dist, preview);
  await mkdir(path.dirname(output), { recursive: true });
  if (ext === '.pdf') {
    run('pdftoppm', ['-f', '1', '-l', '1', '-singlefile', '-scale-to', '960', '-png', source, output.slice(0, -4)]);
  } else {
    run('convert', [source, '-auto-orient', '-resize', '768x1024>', '-colorspace', 'sRGB', '-strip', '-quality', '88', output]);
  }
  updated++;
}
await writeFile(path.join(dist, 'asset-previews.js'), '// Generated by scripts/prepare-media.mjs; edit source paths in site-data.js.\nwindow.ASSET_PREVIEWS = ' + JSON.stringify({ version: 1, files }, null, 2) + ';\n');
console.log(`媒体预览已就绪：${Object.keys(files).length} 个文件，本次生成 ${updated} 个；原照片和 PDF 保持原样。`);
